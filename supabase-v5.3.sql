alter table public.acces_magasin add column if not exists role text not null default 'employe';
alter table public.acces_magasin add column if not exists nom_affichage text;
alter table public.acces_magasin add column if not exists actif boolean not null default true;
alter table public.acces_magasin add column if not exists updated_at timestamptz default now();

-- Normalise les anciennes valeurs éventuelles.
update public.acces_magasin set role = 'employe' where role is null or role not in ('admin','employe');

-- Le premier compte créé pour chaque magasin devient administrateur.
-- Pour un magasin déjà utilisé sur un seul téléphone, ce téléphone devient donc administrateur.
with premiers as (
  select distinct on (a.magasin_id) a.magasin_id, a.user_id
  from public.acces_magasin a
  left join auth.users u on u.id = a.user_id
  order by a.magasin_id, u.created_at asc nulls last, a.user_id
)
update public.acces_magasin a
set role = 'admin', actif = true, updated_at = now()
from premiers p
where a.magasin_id = p.magasin_id and a.user_id = p.user_id;

create table if not exists public.rayons (
  id bigint generated by default as identity primary key,
  magasin_id bigint not null references public.magasins(id) on delete cascade,
  nom text not null,
  position integer not null default 0,
  actif boolean not null default true,
  created_at timestamptz not null default now(),
  unique (magasin_id, nom)
);

insert into public.rayons (magasin_id, nom, position)
select m.id, r.nom, r.position
from public.magasins m
cross join (values
  ('Crèmerie',1),('Charcuterie',2),('Frais',3),('Traiteur',4),
  ('Épicerie',5),('Boucherie',6),('Poissonnerie',7)
) as r(nom,position)
on conflict (magasin_id, nom) do nothing;

alter table public.acces_magasin enable row level security;
alter table public.produits enable row level security;
alter table public.catalogue_produits enable row level security;
alter table public.rayons enable row level security;

grant select, insert, update, delete on public.acces_magasin to authenticated;
grant select, insert, update, delete on public.produits to authenticated;
grant select, insert, update, delete on public.catalogue_produits to authenticated;
grant select, insert, update, delete on public.rayons to authenticated;
