-- Fonctions de contrôle d'accès. SECURITY DEFINER évite la récursion des policies.
create or replace function public.est_membre_magasin(p_magasin_id bigint)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.acces_magasin a
    where a.user_id = auth.uid() and a.magasin_id = p_magasin_id and a.actif = true
  );
$$;

create or replace function public.est_admin_magasin(p_magasin_id bigint)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.acces_magasin a
    where a.user_id = auth.uid() and a.magasin_id = p_magasin_id
      and a.actif = true and a.role = 'admin'
  );
$$;

grant execute on function public.est_membre_magasin(bigint) to authenticated;
grant execute on function public.est_admin_magasin(bigint) to authenticated;

-- Supprime les anciennes policies de ces tables afin d'éviter qu'une ancienne règle plus permissive reste active.
do $$
declare p record;
begin
  for p in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname='public' and tablename in ('acces_magasin','produits','catalogue_produits','rayons')
  loop
    execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end $$;

-- Accès équipe : chacun voit son propre accès ; un admin voit et gère l'équipe du magasin.
create policy "acces lecture soi ou admin" on public.acces_magasin
for select to authenticated
using (user_id = auth.uid() or public.est_admin_magasin(magasin_id));

create policy "acces modification admin" on public.acces_magasin
for update to authenticated
using (public.est_admin_magasin(magasin_id))
with check (public.est_admin_magasin(magasin_id));

-- Produits DLC : tous les membres actifs du magasin peuvent travailler dessus.
create policy "produits lecture membre" on public.produits
for select to authenticated using (public.est_membre_magasin(magasin_id));
create policy "produits ajout membre" on public.produits
for insert to authenticated with check (public.est_membre_magasin(magasin_id));
create policy "produits modif membre" on public.produits
for update to authenticated using (public.est_membre_magasin(magasin_id)) with check (public.est_membre_magasin(magasin_id));
create policy "produits suppression membre" on public.produits
for delete to authenticated using (public.est_membre_magasin(magasin_id));

-- Catalogue : tout membre peut le lire et mémoriser un nouvel EAN ; seul l'admin peut corriger/supprimer.
create policy "catalogue lecture membre" on public.catalogue_produits
for select to authenticated using (public.est_membre_magasin(magasin_id));
create policy "catalogue ajout membre" on public.catalogue_produits
for insert to authenticated with check (public.est_membre_magasin(magasin_id));
create policy "catalogue modif admin" on public.catalogue_produits
for update to authenticated using (public.est_admin_magasin(magasin_id)) with check (public.est_admin_magasin(magasin_id));
create policy "catalogue suppression admin" on public.catalogue_produits
for delete to authenticated using (public.est_admin_magasin(magasin_id));

-- Rayons : visibles par toute l'équipe, modifiables uniquement par l'admin.
create policy "rayons lecture membre" on public.rayons
for select to authenticated using (public.est_membre_magasin(magasin_id));
create policy "rayons ajout admin" on public.rayons
for insert to authenticated with check (public.est_admin_magasin(magasin_id));
create policy "rayons modif admin" on public.rayons
for update to authenticated using (public.est_admin_magasin(magasin_id)) with check (public.est_admin_magasin(magasin_id));
create policy "rayons suppression admin" on public.rayons
for delete to authenticated using (public.est_admin_magasin(magasin_id));
